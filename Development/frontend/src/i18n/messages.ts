function applyBrandName(text: string) {
  return text.replace(/William/g, 'PeetU');
}

export function translateText(language: AppLanguage, text: string, vars?: MessageVars) {
  const template = TEXT_MAP[text]?.[language] || text;
  const rendered = vars
    ? template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ''))
    : template;
  return applyBrandName(rendered);
}

export function getDateFnsLocale(language: AppLanguage) {
  return language === 'zh-CN' ? zhCN : enUS;
}

